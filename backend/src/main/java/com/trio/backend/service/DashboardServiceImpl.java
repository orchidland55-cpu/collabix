    private List<TeamMemberWidget> buildTeamMembers(UUID teamId, UUID workspaceId) {
        List<TeamMember> members = teamMemberRepository.findAllByTeam_IdWithUser(teamId);

        // Batch resolve workspace roles: collect all user IDs and fetch roles in one query
        List<UUID> userIds = members.stream()
                .map(tm -> tm.getUser().getId())
                .collect(Collectors.toList());

        java.util.Map<UUID, String> roleByUserId = workspaceMemberRepository
                .findByWorkspaceIdAndUserIds(workspaceId, userIds)
                .stream()
                .collect(Collectors.toMap(
                        wm -> wm.getUser().getId(),
                        wm -> wm.getRole().name(),
                        (existing, replacement) -> existing
                ));

        return members.stream()
                .map(tm -> {
                    TeamMemberWidget widget = new TeamMemberWidget();
                    User user = tm.getUser();
                    widget.setId(user.getId());
                    widget.setFirstName(user.getFirstName());
                    widget.setLastName(user.getLastName());
                    widget.setEmail(user.getEmail());
                    widget.setWorkspaceRole(roleByUserId.getOrDefault(user.getId(), null));
                    widget.setMemberStatus(tm.getStatus().name());
                    return widget;
                })
                .collect(Collectors.toList());
    }

