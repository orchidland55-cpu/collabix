    private TeamStatisticsWidget buildTeamStatistics(UUID teamId) {
        TeamStatisticsWidget stats = new TeamStatisticsWidget();

        List<TeamMember> members = teamMemberRepository.findAllByTeam_IdWithUser(teamId);
        long totalMembers = members.size();
        long activeMembers = members.stream()
                .filter(m -> WorkspaceMemberStatus.ACTIVE.equals(m.getStatus()))
                .count();
        long pendingInvitations = members.stream()
                .filter(m -> WorkspaceMemberStatus.INVITED.equals(m.getStatus()))
                .count();
        long inactiveMembers = totalMembers - activeMembers - pendingInvitations;

        stats.setTotalMembers(totalMembers);
        stats.setActiveMembers(activeMembers);
        stats.setInactiveMembers(inactiveMembers);
        stats.setPendingInvitations(pendingInvitations);

        return stats;
    }

