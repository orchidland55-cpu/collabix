    private TeamSummaryWidget buildTeamSummaryWidget(UUID workspaceId) {
        TeamSummaryWidget summary = new TeamSummaryWidget();

        long totalTeams = teamRepository.countByWorkspace_Id(workspaceId);
        long activeTeams = teamRepository.countByWorkspace_IdAndStatus(workspaceId, WorkspaceStatus.ACTIVE);

        // Average members per active team: use a single COUNT query across all teams
        // in the workspace to avoid N+1.
        long totalTeamMembers = teamMemberRepository.countByWorkspaceId(workspaceId);
        double averageMembersPerTeam = totalTeams > 0
                ? Math.round((double) totalTeamMembers / totalTeams * 10.0) / 10.0
                : 0.0;

        summary.setTotalTeams(totalTeams);
        summary.setActiveTeams(activeTeams);
        summary.setAverageMembersPerTeam(averageMembersPerTeam);

        return summary;
    }

